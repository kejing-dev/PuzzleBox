"""Imports the 15 boxes of the design package (content.levels) into domain/Levels.kt. The design station solved and
checked them; the app does not invent boxes (levelsNote).

  python3 tools/gen_levels.py "<factory>/apps/puzzle-box/design-package.json"
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app", "src", "main", "java", "io", "embodit", "puzzlebox", "domain", "Levels.kt")
pkg = json.load(open(sys.argv[1], encoding="utf-8"))
lv = pkg["content"]["levels"]
q = lambda s: json.dumps(s, ensure_ascii=False)
rows = []
for L in lv:
    sol = ", ".join('Step(PieceType.%s, "%s")' % (s["piece"], ";".join("%d,%d,%d" % tuple(c) for c in s["cells"])) for s in L["solution"])
    rows.append(
        '        Level(%s, %d, %s, %s, %s, %s, %s, %d, Dims(%d, %d, %d), listOf(%s), listOf(%s), %d),'
        % (q(L["id"]), ["热身", "进阶", "索玛"].index(L["group"]), q(L["nameZh"]), q(L["nameEn"]), q(L["sloganZh"]), q(L["sloganEn"]),
           "true" if L["id"] == "S5" else "false", L["difficulty"], *L["dims"],
           ", ".join("PieceType." + p for p in L["pieces"]), sol, L["essentialSolutions"]))
src = '''package io.embodit.puzzlebox.domain

// Generated by tools/gen_levels.py from the design package content.levels. Do not edit by hand.

/** One placement of the design's known solution, in drop order (cells "x,y,z;..."). */
data class Step(val piece: PieceType, val cellsText: String) {
    val cells: List<Cell> get() = cellsText.split(";").map { Cell.parse(it) }
}

/** One box (design dataModel.level). [group] 0 = 热身 Warm-up, 1 = 进阶 Getting tricky, 2 = 索玛 Soma. */
data class Level(
    val id: String,
    val group: Int,
    val nameZh: String,
    val nameEn: String,
    val sloganZh: String,
    val sloganEn: String,
    val soma: Boolean,
    val difficulty: Int,
    val dims: Dims,
    val pieces: List<PieceType>,
    val solution: List<Step>,
    val essential: Int,
)

object Levels {
    val ALL: List<Level> = listOf(
%s
    )

    fun byId(id: String): Level? = ALL.firstOrNull { it.id == id }
    fun indexOf(id: String): Int = ALL.indexOfFirst { it.id == id }.coerceAtLeast(0)
}
''' % "\n".join(rows)
open(OUT, "w", encoding="utf-8").write(src)
print("wrote", OUT, len(lv), "levels")
